-- Restaurant ABC: one restaurant per letter; round_no = pass through the alphabet (1 = first time through).
CREATE TABLE IF NOT EXISTS personal_tracking.abc_visit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_no    SMALLINT NOT NULL DEFAULT 1 CHECK (round_no BETWEEN 1 AND 99),
    letter      TEXT NOT NULL CHECK (letter ~ '^[A-Z]$'),
    name        TEXT NOT NULL,
    location    TEXT,
    rating      SMALLINT CHECK (rating BETWEEN 1 AND 5),
    visited_on  DATE,
    notes       TEXT,
    place_id    TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (round_no, letter)
);
