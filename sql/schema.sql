-- Schema for ChipJar in Azure PostgreSQL (database: personal_storage).
-- Idempotent; safe to re-run. Objects are owned by the personal_tracking_app role.
--
-- One-time bootstrap performed as server admin (already applied):
--   CREATE ROLE personal_tracking_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
--   GRANT CONNECT ON DATABASE personal_storage TO personal_tracking_app;
--   CREATE SCHEMA personal_tracking AUTHORIZATION personal_tracking_app;
--   ALTER ROLE personal_tracking_app SET search_path = personal_tracking, public;

CREATE TABLE IF NOT EXISTS personal_tracking.household_member (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE
);

-- Managed from /manage: card colour, home-page order, and whether the member shows on chips/allowance/meds pages.
ALTER TABLE personal_tracking.household_member ADD COLUMN IF NOT EXISTS color TEXT;
ALTER TABLE personal_tracking.household_member ADD COLUMN IF NOT EXISTS sort_order INTEGER NOT NULL DEFAULT 0;
ALTER TABLE personal_tracking.household_member ADD COLUMN IF NOT EXISTS tracked BOOLEAN NOT NULL DEFAULT TRUE;

WITH ranked AS (
    SELECT id, row_number() OVER (ORDER BY sort_order, name) - 1 AS rn
    FROM personal_tracking.household_member
)
UPDATE personal_tracking.household_member hm
SET color = (ARRAY['#d9643a', '#1b998b', '#6c5ce7', '#e4a010', '#e2559c', '#3b82c4'])[r.rn % 6 + 1]
FROM ranked r
WHERE hm.id = r.id AND hm.color IS NULL;

ALTER TABLE personal_tracking.household_member ALTER COLUMN color SET DEFAULT '#d9643a';
ALTER TABLE personal_tracking.household_member ALTER COLUMN color SET NOT NULL;
ALTER TABLE personal_tracking.household_member DROP CONSTRAINT IF EXISTS household_member_color_check;
ALTER TABLE personal_tracking.household_member
    ADD CONSTRAINT household_member_color_check CHECK (color ~ '^#[0-9a-f]{6}$');

-- App-wide preferences edited on /manage (keys/defaults in app/db.py SETTING_DEFAULTS).
CREATE TABLE IF NOT EXISTS personal_tracking.app_setting (
    key         TEXT PRIMARY KEY,
    value       TEXT NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS personal_tracking.incentives (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    description TEXT,
    points      INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS personal_tracking.medications (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    description TEXT,
    dose        INTEGER NOT NULL
);

-- Event log for all trackers. ts = user-facing event time; created_at = insert time.
CREATE TABLE IF NOT EXISTS personal_tracking.activity (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    household_member_id INTEGER NOT NULL REFERENCES personal_tracking.household_member(id),
    category            TEXT NOT NULL
                        CHECK (category IN ('incentive', 'allowance', 'medication', 'other')),
    activity_type       TEXT NOT NULL,
    amount              NUMERIC(12, 2),
    notes               TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_activity_member_category_ts
    ON personal_tracking.activity (household_member_id, category, ts DESC, id DESC);

-- Decision spinners ("Movie Night", "Dinner Out"): each member contributes one pick per round,
-- a spin records the winner. kind='movie' enables Jellyfin suggestions, kind='restaurant' Google Places.
CREATE TABLE IF NOT EXISTS personal_tracking.spinner (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    emoji       TEXT NOT NULL DEFAULT '🎯',
    kind        TEXT NOT NULL DEFAULT 'generic',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE personal_tracking.spinner DROP CONSTRAINT IF EXISTS spinner_kind_check;
ALTER TABLE personal_tracking.spinner
    ADD CONSTRAINT spinner_kind_check CHECK (kind IN ('generic', 'movie', 'restaurant'));

CREATE TABLE IF NOT EXISTS personal_tracking.spinner_pick (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spinner_id          INTEGER NOT NULL REFERENCES personal_tracking.spinner(id) ON DELETE CASCADE,
    household_member_id INTEGER NOT NULL REFERENCES personal_tracking.household_member(id),
    label               TEXT NOT NULL,
    jellyfin_item_id    TEXT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (spinner_id, household_member_id)
);

-- options = JSONB snapshot of the picks that were on the wheel: [{"label","member_id","member","jellyfin_item_id","place_id"}]
CREATE TABLE IF NOT EXISTS personal_tracking.spin_result (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spinner_id          INTEGER NOT NULL REFERENCES personal_tracking.spinner(id) ON DELETE CASCADE,
    ts                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    label               TEXT NOT NULL,
    household_member_id INTEGER REFERENCES personal_tracking.household_member(id),
    jellyfin_item_id    TEXT,
    options             JSONB NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_spin_result_spinner_ts
    ON personal_tracking.spin_result (spinner_id, ts DESC, id DESC);

-- Google Places id for restaurant picks/results
ALTER TABLE personal_tracking.spinner_pick ADD COLUMN IF NOT EXISTS place_id TEXT;
ALTER TABLE personal_tracking.spin_result ADD COLUMN IF NOT EXISTS place_id TEXT;

